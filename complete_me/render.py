"""Render a Command model as fish and bash completion scripts.

Help text is untrusted and these files get sourced into an interactive shell,
so every name is validated and every description is quoted for the target shell.
"""
from __future__ import annotations

import hashlib
import re

from . import __version__
from .model import Command, Option

TOKEN = re.compile(r"^[A-Za-z0-9_][\w.:@+,=%/-]*$")


def ident(name: str) -> str:
    return re.sub(r"\W", "_", name) + "_" + hashlib.sha1(name.encode()).hexdigest()[:6]


def fq(s: str) -> str:
    """Single-quote for fish."""
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def sq(s: str) -> str:
    """Single-quote for POSIX shells."""
    return "'" + s.replace("'", "'\\''") + "'"


def clean_desc(s: str) -> str:
    s = re.sub(r"[\x00-\x1f\x7f]", " ", s or "").strip()
    return s[:100]


FISH_KIND = {
    "dir": "-xa '(__fish_complete_directories (commandline -ct))'",
    "user": "-xa '(__fish_complete_users)'",
    "group": "-xa '(__fish_complete_groups)'",
    "host": "-xa '(__fish_print_hostnames)'",
    "pid": "-xa '(__fish_complete_pids)'",
    "command": "-xa '(__fish_complete_command)'",
    "number": "-x",
    "file": "-rF",
}


def safe_walk(cmd: Command, path: tuple[str, ...] = ()):
    """Like Command.walk, but drops any subtree whose name is not a plain token."""
    yield path, cmd
    for name, sub in cmd.subcommands.items():
        if TOKEN.match(name) and "/" not in name:
            yield from safe_walk(sub, path + (name,))


def fish(cmd: Command) -> str:
    name = cmd.name
    if not TOKEN.match(name) or "/" in name:
        raise ValueError(f"refusing to render completions for unsafe name {name!r}")
    cid = ident(name)
    out = [
        f"# Generated by complete-me {__version__} from: {', '.join(cmd.sources) or 'unknown'}.",
        f"# Regenerate: complete-me gen --force {name}    Remove: complete-me forget {name}",
    ]
    tree, aliases, argopts = [], [], []
    for path, node in safe_walk(cmd):
        tree.append(" ".join(path))
        for a in node.aliases:
            if TOKEN.match(a):
                aliases.append(" ".join(path[:-1] + (a,)) + "=" + path[-1])
        for o in node.options:
            if o.arg and not o.arg_optional:
                argopts.extend(f for f in o.flags() if TOKEN.match(f.lstrip("-")))
    out.append(f"set -g __cm_tree_{cid} " + " ".join(fq(t) for t in tree))
    out.append(f"set -g __cm_alias_{cid} " + " ".join(fq(a) for a in aliases))
    out.append(f"set -g __cm_argopts_{cid} " + " ".join(fq(a) for a in dict.fromkeys(argopts)))

    vfn = 0
    # fish only autosuggests (grey text) from completions with no condition and no command
    # substitution, so flat commands get plain static lines and inline enum values.
    flat = not cmd.subcommands
    for path, node in safe_walk(cmd):
        cond = fq(f"__complete_me_at {cid}" + "".join(" " + p for p in path))
        base = f"complete -c {name}" if flat else f"complete -c {name} -n {cond}"
        for sub_name, sub in node.subcommands.items():
            if not TOKEN.match(sub_name):
                continue
            d = clean_desc(sub.desc) or "subcommand"
            out.append(f"{base} -f -a {fq(sub_name)} -d {fq(d)}")
            for a in sub.aliases:
                if TOKEN.match(a):
                    out.append(f"{base} -f -a {fq(a)} -d {fq('alias for ' + sub_name)}")
        words = " ".join((name,) + path)
        hist = fq("(__complete_me_hist_args " + words + ")")
        if node.subcommands and not node.takes_files:
            out.append(f"{base} -f")
        elif node.takes_files:
            out.append(f"{base} -k -a {hist}")
        else:
            out.append(f"{base} -f -k -a {hist}")
        for o in node.options:
            parts = []
            for s in o.shorts:
                if re.fullmatch(r"[A-Za-z0-9?#]", s):
                    parts.append(f"-s {fq(s)}")
            for l in o.longs:
                if TOKEN.match(l):
                    parts.append(f"-l {fq(l)}")
            for old in o.olds:
                if TOKEN.match(old):
                    parts.append(f"-o {fq(old)}")
            if not parts:
                continue
            line = f"{base} {' '.join(parts)}"
            if o.desc:
                line += f" -d {fq(clean_desc(o.desc))}"
            if o.values and flat:
                out.append(line + " -x")
                for v, d in o.values:
                    if TOKEN.match(v):
                        out.append(f"{base} {' '.join(parts)} -x -a {fq(v)}" + (f" -d {fq(clean_desc(d))}" if d else ""))
                continue
            if o.values:
                vfn += 1
                fn = f"__cm_v_{cid}_{vfn}"
                rows = " ".join(f"{fq(v)} {fq(clean_desc(d))}" for v, d in o.values if TOKEN.match(v))
                out.append(f"function {fn}; printf '%s\\t%s\\n' {rows}; end")
                line += f" -x -a '({fn})'"
            elif o.arg:
                flag = o.flags()[0]
                hist = f"(__complete_me_hist_optvals {name} {flag})"
                kind = FISH_KIND.get(o.kind)
                if kind is None or kind == "-x":
                    line += f" -x -a {fq(hist)}" if kind == "-x" else f" -r -a {fq(hist)}"
                elif kind == "-rF":
                    line += " -rF"
                else:
                    line += " " + kind
            out.append(line)
    return "\n".join(out) + "\n"


def bash(cmd: Command) -> str:
    """A self-contained bash completion function: subcommand tree, options, enum values."""
    name = cmd.name
    if not TOKEN.match(name) or "/" in name:
        raise ValueError(f"refusing to render completions for unsafe name {name!r}")
    fn = "_complete_me_" + re.sub(r"\W", "_", name)
    cases_words, cases_vals = [], []
    for path, node in safe_walk(cmd):
        key = " ".join(path)
        words = list(node.subcommands)
        for s in node.subcommands.values():
            words += s.aliases
        for o in node.options:
            words += [f for f in o.flags() if TOKEN.match(f.lstrip("-"))]
            if o.values:
                vals = " ".join(v for v, _ in o.values if TOKEN.match(v))
                for f in o.flags():
                    cases_vals.append(f"        {sq(key + '|' + f)}) COMPREPLY=($(compgen -W {sq(vals)} -- \"$cur\")); return;;")
        files = "1" if node.takes_files and not node.subcommands else "0"
        cases_words.append(f"        {sq(key)}) words={sq(' '.join(w for w in words if TOKEN.match(w.lstrip('-'))))}; files={files};;")
    tree = " ".join(sq(" ".join(p)) for p, _ in safe_walk(cmd) if p)
    return f"""# Generated by complete-me {__version__} from: {', '.join(cmd.sources)}.
{fn}() {{
    local cur="${{COMP_WORDS[COMP_CWORD]}}" prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    local path="" i w words files
    local -a tree=({tree})
    for ((i = 1; i < COMP_CWORD; i++)); do
        w="${{COMP_WORDS[i]}}"
        [[ $w == -* ]] && continue
        local cand="${{path:+$path }}$w" t found=0
        for t in "${{tree[@]}}"; do [[ $t == "$cand" ]] && found=1 && break; done
        ((found)) && path="$cand" || break
    done
    case "$path|$prev" in
{chr(10).join(cases_vals) or '        __none__) ;;'}
    esac
    case "$path" in
{chr(10).join(cases_words)}
        *) words=""; files=1;;
    esac
    COMPREPLY=($(compgen -W "$words" -- "$cur"))
    if ((files)) && [[ $cur != -* ]]; then
        COMPREPLY+=($(compgen -f -- "$cur"))
    fi
}}
complete -o bashdefault -o default -F {fn} {name}
"""
